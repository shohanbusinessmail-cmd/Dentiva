export class I18nMain {
  private lang: 'en' | 'bn' = 'en';
  private data: Record<string, Record<string, string>> = { en, bn };

  setLang(lang: 'en' | 'bn') {
    if (this.data[lang]) this.lang = lang;
  }

  getLang(): 'en' | 'bn' { return this.lang; }

  t(key: string, vars?: Record<string, string | number>): string {
    const str = this.data[this.lang]?.[key] || this.data.en[key] || key;
    if (!vars) return str;
    return str.replace(/\{\{(\w+)\}\}/g, (_, k) => vars[k] !== undefined ? String(vars[k]) : '');
  }

  all(): Record<string, string> {
    return { ...this.data[this.lang] };
  }
}